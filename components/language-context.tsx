export type Language = "en" | "bn";
export type TranslationKey = keyof typeof translations | keyof typeof englishTranslations;

type LanguageContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: string) => string;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);
const LANGUAGE_STORAGE_KEY = "hbca-language";
const LANGUAGE_CHANGE_EVENT = "hbca-language-change";

function subscribeToLanguageChange(onChange: () => void) {
  window.addEventListener("storage", onChange);
  window.addEventListener(LANGUAGE_CHANGE_EVENT, onChange);
  return () => {
    window.removeEventListener("storage", onChange);
    window.removeEventListener(LANGUAGE_CHANGE_EVENT, onChange);
  };
}

function getStoredLanguage(): Language {
  const language = window.localStorage.getItem(LANGUAGE_STORAGE_KEY);
  return language === "bn" ? "bn" : "en";
}

function getServerLanguage(): Language {
  return "en";
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const language = useSyncExternalStore(subscribeToLanguageChange, getStoredLanguage, getServerLanguage);

  useEffect(() => {
    document.documentElement.lang = language;
  }, [language]);

  const value = useMemo(
    () => ({
      language,
      setLanguage: (nextLanguage: Language) => {
        window.localStorage.setItem(LANGUAGE_STORAGE_KEY, nextLanguage);
        window.dispatchEvent(new Event(LANGUAGE_CHANGE_EVENT));
      },
      t: (key: string) => {
        const text = String(key);
        const isBangla = /[\u0980-\u09ff]/.test(text);
        if (language === "bn") {
          return isBangla ? text : translations[key as keyof typeof translations] ?? text;
        }
        return isBangla
          ? translations[key as keyof typeof translations] ?? englishTranslations[key] ?? text
          : text;
      },
    }),
    [language],
  );

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) {
    throw new Error("useLanguage must be used inside LanguageProvider");
  }
  return context;
}
